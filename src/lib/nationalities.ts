const SUBDIVISIONS: Record<string, Record<Locale, string>> = {
  "gb-eng": { es: "Inglaterra", en: "England" },
  "gb-sct": { es: "Escocia", en: "Scotland" },
  "gb-wls": { es: "Gales", en: "Wales" },
  "gb-nir": { es: "Irlanda del Norte", en: "Northern Ireland" },
};

export interface NationalityInfo {
  /** Ruta de la imagen de la bandera. */
  flagSrc: string;
  /** Nombre del país en el idioma de la interfaz. */
  name: string;
}

/** Bandera y nombre de una nacionalidad, o null si falta el dato o no hay bandera para ese país. */
export function nationalityInfo(
  nationality: string | null | undefined,
  locale: Locale,
): NationalityInfo | null {
  const code = nationality ? FLAG_CODES[nationality] : undefined;
  if (!code) return null;
  const name =
    SUBDIVISIONS[code]?.[locale] ??
    new Intl.DisplayNames(locale, { type: "region" }).of(code.toUpperCase()) ??
    nationality!;
  return { flagSrc: `/flags/${code}.png`, name };
}
